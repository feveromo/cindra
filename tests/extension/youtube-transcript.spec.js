test('manual tracks use metadata, and XML preserves entities, non-English text, and the final cue', async () => {
  const { context, serviceWorker } = await launchExtensionContext();
  try {
    const requested = [];
    const page = await context.newPage();
    const tracks = [
      { languageCode: 'fr', kind: 'asr', baseUrl: `https://www.youtube.com/api/timedtext?v=${VIDEO_ID}&track=fr` },
      { languageCode: 'en', kind: 'asr', baseUrl: `https://www.youtube.com/api/timedtext?v=${VIDEO_ID}&track=auto` },
      { languageCode: 'en', baseUrl: `https://www.youtube.com/api/timedtext?v=${VIDEO_ID}&track=manual&fmt=srv3` }
    ];
    await page.route('https://www.youtube.com/**', route => {
      if (route.request().url().includes('/api/timedtext')) {
        requested.push(route.request().url());
        return route.fulfill({ contentType: 'text/xml', body: '<timedtext><body><p t="0" d="2000">Café &amp; <s>日本語.</s></p><p t="18000" d="2000">Final cue.</p></body></timedtext>' });
      }
      return route.fulfill({ contentType: 'text/html', body: fixtureHtml(playerResponse(VIDEO_ID, tracks)) });
    });
    await page.goto(URL);
    const result = await extract(serviceWorker);
    expect(result).toMatchObject({ success: true, language: 'en', isAutoGenerated: false, segmentCount: 2 });
    expect(result.transcript).toBe('Transcript:\n\nCafé & 日本語.\n\nFinal cue.');
    expect(requested).toEqual([tracks[2].baseUrl]);
  } finally { await context.close(); }
});


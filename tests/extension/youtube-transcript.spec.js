const { test, expect } = require('@playwright/test');
const { launchExtensionContext, extensionId } = require('./helpers.js');

const VIDEO_ID = 'cindra00001';
const URL = `https://www.youtube.com/watch?v=${VIDEO_ID}`;

function playerResponse(videoId = VIDEO_ID, tracks = [{ languageCode: 'en', kind: 'asr' }]) {
  return {
    videoDetails: { videoId, title: 'Transcript fixture', author: 'Fixture channel', lengthSeconds: '20' },
    playabilityStatus: { status: 'OK' },
    captions: { playerCaptionsTracklistRenderer: { captionTracks: tracks.map(track => ({
      baseUrl: `https://www.youtube.com/api/timedtext?v=${videoId}&lang=${track.languageCode}`,
      ...track
    })) } }
  };
}

function fixtureHtml(response = playerResponse(), extra = '') {
  return `<!doctype html><html><head><title>Transcript fixture - YouTube</title></head><body>
    <div id="movie_player"></div><ytd-watch-flexy video-id="${VIDEO_ID}">
    <ytd-watch-metadata><div id="above-the-fold"><div id="top-row"><div id="subscribe-button"></div></div></div></ytd-watch-metadata>
    <button aria-label="Show transcript" onclick="window.panelClicks++">Show transcript</button>
    <button class="ytp-subtitles-button" onclick="window.ccClicks++">CC</button>
    </ytd-watch-flexy><script>
    window.panelClicks = 0; window.ccClicks = 0;
    window.fixturePlayer = ${JSON.stringify(response)};
    document.getElementById('movie_player').getPlayerResponse = () => window.fixturePlayer;
    document.getElementById('movie_player').getVideoData = () => ({ video_id: window.fixturePlayer?.videoDetails.videoId });
    </script>${extra}</body></html>`;
}

const captions = { events: [
  { tStartMs: 0, dDurationMs: 2000, segs: [{ utf8: 'First ' }, { utf8: 'sentence.' }] },
  { tStartMs: 5000, dDurationMs: 2000, segs: [{ utf8: 'I really really mean café & 日本語.' }] },
  { tStartMs: 18000, dDurationMs: 2000, segs: [{ utf8: 'Final sentence.' }] }
] };

async function extract(serviceWorker, videoId = VIDEO_ID) {
  return serviceWorker.evaluate(async ({ videoId }) => {
    const tabs = await chrome.tabs.query({ url: 'https://www.youtube.com/*' });
    return chrome.tabs.sendMessage(tabs[0].id, { action: 'extractTranscript', videoId });
  }, { videoId });
}

test('quiet auto captions use current MAIN-world player data without opening or scrolling the page', async () => {
  const { context, serviceWorker } = await launchExtensionContext();
  try {
    let watchRequests = 0;
    let captionRequests = 0;
    const page = await context.newPage();
    await page.route('https://www.youtube.com/**', route => {
      if (route.request().url().includes('/api/timedtext')) {
        captionRequests++;
        return route.fulfill({ contentType: 'application/json', body: JSON.stringify(captions) });
      }
      watchRequests++;
      return route.fulfill({ contentType: 'text/html', body: fixtureHtml() });
    });
    await page.goto(URL);
    const result = await extract(serviceWorker);
    expect(result, result.error).toMatchObject({ success: true, videoId: VIDEO_ID, complete: true, isAutoGenerated: true });
    expect(result.transcript).toBe('Transcript:\n\nFirst sentence.\n\nI really really mean café & 日本語.\n\nFinal sentence.');
    expect(await page.evaluate(() => [window.panelClicks, window.ccClicks, window.scrollY])).toEqual([0, 0, 0]);
    expect(watchRequests).toBe(1);
    expect(captionRequests).toBe(1);
  } finally {
    await context.close();
  }
});

function currentWatchScript(extra = '') {
  return `<script>
    const watch = document.querySelector('ytd-watch-flexy');
    watch.data = { currentVideoEndpoint: { watchEndpoint: { videoId: '${VIDEO_ID}' } } };
    window.ytcfg = { data_: { INNERTUBE_CONTEXT: { client: { clientName: 'WEB', clientVersion: 'test' } } } };
    ${extra}
  </script>`;
}

function modelSegments(count = 3) {
  return Array.from({ length: count }, (_, index) => ({ transcriptSegmentViewModel: {
    timestamp: `${Math.floor(index / 60)}:${String(index % 60).padStart(2, '0')}`,
    simpleText: `Segment ${index}.`
  } }));
}

test('empty captions fall through to the current transcript command without opening its panel', async () => {
  const { context, serviceWorker } = await launchExtensionContext();
  try {
    const requests = [];
    const page = await context.newPage();
    await page.route('https://www.youtube.com/**', route => {
      const url = route.request().url();
      requests.push(new globalThis.URL(url).pathname);
      if (url.includes('/api/timedtext')) return route.fulfill({ body: '' });
      if (url.includes('/youtubei/v1/get_panel')) {
        expect(route.request().postDataJSON()).toMatchObject({ panelId: 'current-transcript-panel', params: 'page-generated-params' });
        return route.fulfill({ contentType: 'application/json', body: JSON.stringify({ contents: modelSegments(900) }) });
      }
      return route.fulfill({ contentType: 'text/html', body: fixtureHtml(playerResponse(),
        '<ytd-video-description-transcript-section-renderer></ytd-video-description-transcript-section-renderer>' +
        currentWatchScript(`document.querySelector('ytd-video-description-transcript-section-renderer').data = {
          showEngagementPanelEndpoint: { identifier: { tag: 'current-transcript-panel' }, globalConfiguration: { params: 'page-generated-params' } }
        };`)) });
    });
    await page.goto(URL);
    const result = await extract(serviceWorker);
    expect(result, result.error).toMatchObject({ success: true, source: 'transcript', complete: true, segmentCount: 900 });
    expect(result.transcript.startsWith('Transcript:\n\nSegment 0.')).toBe(true);
    expect(result.transcript.endsWith('Segment 899.')).toBe(true);
    expect(result.transcript.match(/Segment \d+\./g)).toHaveLength(900);
    expect(requests).toEqual(['/watch', '/api/timedtext', '/youtubei/v1/get_panel']);
    expect(await page.evaluate(() => [window.panelClicks, window.ccClicks, window.scrollY])).toEqual([0, 0, 0]);
  } finally { await context.close(); }
});


test('an absent player does not beat a successful fresh watch-page caption retrieval', async () => {
  const { context, serviceWorker } = await launchExtensionContext();
  try {
    let watchRequests = 0;
    const page = await context.newPage();
    await page.route('https://www.youtube.com/**', async route => {
      if (route.request().url().includes('/api/timedtext')) {
        return route.fulfill({ contentType: 'application/json', body: JSON.stringify(captions) });
      }
      watchRequests++;
      if (watchRequests > 1) {
        await new Promise(resolve => setTimeout(resolve, 100));
        return route.fulfill({ contentType: 'text/html', body: `<script>var ytInitialPlayerResponse = ${JSON.stringify(playerResponse())};</script>` });
      }
      return route.fulfill({ contentType: 'text/html', body: fixtureHtml(null).replace(/<button[\s\S]*?<\/button>/g, '') });
    });
    await page.goto(URL);
    const result = await extract(serviceWorker);
    expect(result, result.error).toMatchObject({ success: true, videoId: VIDEO_ID, complete: true });
    expect(result.transcript).toContain('Final sentence.');
    expect(watchRequests).toBe(2);
  } finally {
    await context.close();
  }
});
